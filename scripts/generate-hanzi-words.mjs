import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import hskVocabulary from 'hsk3.1-syllabus'
import { pinyin } from 'pinyin-pro'
import subtlexChWf from 'subtlex-ch-wf'

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)))
const outputPath = join(
  rootDir,
  'src',
  'data',
  'hanziWordLexicon.ts',
)
const hanziPattern = /^[\u3400-\u9fff]{2,4}$/u
const levelOrder = ['1', '2', '3', '4', '5', '6', '7-9']

const flattenVocabulary = (items) => {
  const flat = []
  const visit = (entry) => {
    if (Array.isArray(entry) && Array.isArray(entry[0])) {
      entry.forEach(visit)
      return
    }
    flat.push(entry)
  }
  items.forEach(visit)
  return flat
}

const frequencyByWord = new Map()
for (const row of subtlexChWf.data) {
  if (typeof row.Word === 'string' && typeof row.WCount === 'number') {
    frequencyByWord.set(row.Word, row.WCount)
  }
}

const entriesByWord = new Map()
for (const entry of flattenVocabulary(hskVocabulary)) {
  const [, level, word, , partsOfSpeech] = entry
  if (
    typeof word !== 'string' ||
    !hanziPattern.test(word) ||
    entriesByWord.has(word)
  ) {
    continue
  }
  entriesByWord.set(word, {
    word,
    level: levelOrder.indexOf(level),
    sequence: entry[0],
    partsOfSpeech,
  })
}

const words = []
for (const entry of entriesByWord.values()) {
  const characters = Array.from(entry.word)
  const untoned = pinyin(entry.word, {
    type: 'array',
    toneType: 'none',
    v: true,
  })
  const toned = pinyin(entry.word, {
    type: 'array',
    toneType: 'symbol',
    v: true,
  })

  if (
    untoned.length !== characters.length ||
    toned.length !== characters.length ||
    !untoned.every((syllable) => /^[a-z]+$/u.test(syllable))
  ) {
    continue
  }

  const key = untoned.join('')
  if (key.length > 24) {
    continue
  }

  words.push({
    key,
    word: entry.word,
    syllables: toned.join(' '),
    frequency: frequencyByWord.get(entry.word) ?? 0,
    level: entry.level === -1 ? 99 : entry.level,
    sequence: entry.sequence,
  })
}

words.sort(
  (left, right) =>
    right.frequency - left.frequency ||
    left.level - right.level ||
    left.sequence - right.sequence,
)

const lines = words.map(
  (entry) =>
    `  [${JSON.stringify(entry.key)}, ${JSON.stringify(entry.word)}, ${JSON.stringify(entry.syllables)}],`,
)

const source = `// Generated by scripts/generate-hanzi-words.mjs.
// Word source: HSK 3.1 syllabus (MIT package hsk3.1-syllabus).
// Ordering: SUBTLEX-CH-WF frequency (MIT package subtlex-ch-wf), then HSK order.
// See THIRD_PARTY_NOTICES.md for attribution.

export type WordLexiconEntry = readonly [
  key: string,
  word: string,
  syllables: string,
]

export const WORD_LEXICON: readonly WordLexiconEntry[] = [
${lines.join('\n')}
]
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, source, 'utf8')
console.log(`Generated ${words.length} word entries in ${outputPath}`)
