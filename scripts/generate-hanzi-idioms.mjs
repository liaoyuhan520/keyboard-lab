import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { pinyin } from 'pinyin-pro'
import initSqlJs from 'sql.js'
import charFrequency from 'subtlex-ch-chr'
import wordFrequency from 'subtlex-ch-wf'

const require = createRequire(import.meta.url)
const rootDir = dirname(dirname(fileURLToPath(import.meta.url)))
const databasePath = join(rootDir, 'data', 'idioms.db')
const outputPath = join(rootDir, 'src', 'data', 'hanziIdiomLexicon.ts')
const hanziPattern = /^[\u3400-\u9fff]{4,}$/u

if (!existsSync(databasePath)) {
  throw new Error(
    `Idiom database not found at ${databasePath}. The idiom lexicon is generated from data/idioms.db.`,
  )
}

const characterRank = new Map(
  [
    ...new Set(
      charFrequency.data
        .filter(
          (row) =>
            typeof row.Character === 'string' &&
            Array.from(row.Character).length === 1 &&
            /\p{Script=Han}/u.test(row.Character) &&
            row.CHRCount > 0,
        )
        .sort((left, right) => right.CHRCount - left.CHRCount)
        .map((row) => row.Character),
    ),
  ].map((character, index) => [character, index]),
)
const wordFrequencyMap = new Map(
  wordFrequency.data
    .filter(
      (row) =>
        typeof row.Word === 'string' && typeof row.WCount === 'number',
    )
    .map((row) => [row.Word, row.WCount]),
)

const SQL = await initSqlJs({
  locateFile: (file) =>
    join(dirname(require.resolve('sql.js')), '..', 'dist', file),
})
const database = new SQL.Database(readFileSync(databasePath))
const result = database.exec('SELECT word FROM idioms ORDER BY word')
database.close()

const idioms = new Set()
for (const [word] of result[0]?.values ?? []) {
  if (typeof word === 'string' && hanziPattern.test(word)) {
    idioms.add(word)
  }
}

const entries = []

for (const word of idioms) {
  const characters = Array.from(word)
  const untoned = pinyin(word, {
    type: 'array',
    toneType: 'none',
    v: true,
  })
  const toned = pinyin(word, {
    type: 'array',
    toneType: 'symbol',
    v: true,
  })

  if (
    untoned.length !== characters.length ||
    toned.length !== characters.length ||
    !untoned.every((syllable) => /^[a-z]+$/u.test(syllable))
  ) {
    continue
  }

  const key = untoned.join('')
  if (key.length > 24) {
    continue
  }

  const characterRanks = characters.map(
    (character) => characterRank.get(character) ?? 99999,
  )

  entries.push({
    key,
    word,
    syllables: toned.join(' '),
    frequency: wordFrequencyMap.get(word) ?? 0,
    characterScore: characterRanks.reduce(
      (sum, rank) => sum + rank,
      0,
    ),
  })
}

entries.sort(
  (left, right) =>
    right.frequency - left.frequency ||
    left.characterScore - right.characterScore ||
    left.word.localeCompare(right.word, 'zh-CN'),
)

const lines = entries.map(
  (entry) =>
    `  [${JSON.stringify(entry.key)}, ${JSON.stringify(entry.word)}, ${JSON.stringify(entry.syllables)}, ${entry.frequency}],`,
)

const source = `// Generated by scripts/generate-hanzi-idioms.mjs.
// Idiom source: data/idioms.db (table: idioms; four or more Hanzi).
// Pinyin is generated with pinyin-pro so the existing exact-pinyin matching
// stays stable. Definitions are exported separately from the same database.
// The fourth tuple field is the SUBTLEX-CH-WF word count (0 when absent).
// See docs/idiom-definitions.md and THIRD_PARTY_NOTICES.md.

export type IdiomLexiconEntry = readonly [
  key: string,
  word: string,
  syllables: string,
  frequency: number,
]

export const IDIOM_LEXICON: readonly IdiomLexiconEntry[] = [
${lines.join('\n')}
]
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, source, 'utf8')
console.log(`Generated ${entries.length} idiom entries in ${outputPath}`)
