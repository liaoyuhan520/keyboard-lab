import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import initSqlJs from 'sql.js'

const require = createRequire(import.meta.url)
const rootDir = dirname(dirname(fileURLToPath(import.meta.url)))
const databasePath = join(rootDir, 'data', 'idioms.db')
const outputPath = join(rootDir, 'src', 'data', 'hanziIdiomDefinitions.ts')
const hanziPattern = /^[\u3400-\u9fff]{4,}$/u

const cleanText = (value) => {
  if (typeof value !== 'string') {
    return ''
  }

  return value
    .replace(/<br\s*\/?>/giu, '\n')
    .replace(/<\/p>/giu, '\n')
    .replace(/<[^>]+>/gu, '')
    .replace(/&nbsp;/giu, ' ')
    .replace(/&amp;/giu, '&')
    .replace(/&lt;/giu, '<')
    .replace(/&gt;/giu, '>')
    .replace(/&quot;/giu, '"')
    .replace(/&#39;/giu, "'")
    .replace(/\r\n?/gu, '\n')
    .replace(/[ \t]+/gu, ' ')
    .replace(/\n{2,}/gu, '\n')
    .trim()
}

const writeEmptyModule = (reason) => {
  const source = `// Generated by scripts/generate-hanzi-idiom-definitions.mjs.
// No definitions were exported: ${reason}
// The UI falls back to the existing no-definition behavior.

export type IdiomDefinition = {
  readonly brief: string
  readonly detail: string
}

export const IDIOM_DEFINITION_COUNT = 0

export const findIdiomDefinition = (
  _word: string,
): IdiomDefinition | null => null
`
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, source, 'utf8')
  console.warn(
    `[idiom definitions] ${reason}. Generated an empty definition module.`,
  )
}

if (!existsSync(databasePath)) {
  writeEmptyModule(`database not found at ${databasePath}`)
  process.exit(0)
}

let entries = []

try {
  const SQL = await initSqlJs({
    locateFile: (file) =>
      join(dirname(require.resolve('sql.js')), '..', 'dist', file),
  })
  const database = new SQL.Database(readFileSync(databasePath))
  const result = database.exec(
    'SELECT word, brief, detailed FROM idioms ORDER BY word',
  )
  database.close()

  const rows = result[0]?.values ?? []
  const seen = new Set()

  for (const [word, briefValue, detailedValue] of rows) {
    if (
      typeof word !== 'string' ||
      !hanziPattern.test(word) ||
      seen.has(word)
    ) {
      continue
    }

    const brief = cleanText(briefValue)
    const detailed = cleanText(detailedValue)
    const primary = brief || detailed
    if (!primary) {
      continue
    }

    const detail = detailed && detailed !== primary ? detailed : ''

    seen.add(word)
    entries.push([word, primary, detail])
  }
} catch (error) {
  console.warn(
    `[idiom definitions] Failed to read ${databasePath}: ${error instanceof Error ? error.message : String(error)}`,
  )
  entries = []
}

if (entries.length === 0) {
  writeEmptyModule('the database did not yield usable four-character definitions')
  process.exit(0)
}

const lines = entries.map(
  ([word, brief, detail]) =>
    `  [${JSON.stringify(word)}, ${JSON.stringify(brief)}, ${JSON.stringify(detail)}],`,
)

const source = `// Generated by scripts/generate-hanzi-idiom-definitions.mjs.
// Source: data/idioms.db (table: idioms; fields: brief, detailed).
// Only four-or-more-character heads are exported; the idiom lexicon remains
// the authority for pinyin matching. Loaded on demand by the Hanzi practice page.
// See docs/idiom-definitions.md and THIRD_PARTY_NOTICES.md.

export type IdiomDefinition = {
  readonly brief: string
  readonly detail: string
}

export const IDIOM_DEFINITION_COUNT = ${entries.length}

const IDIOM_DEFINITIONS: readonly (readonly [
  word: string,
  brief: string,
  detail: string,
])[] = [
${lines.join('\n')}
]

const DEFINITION_BY_WORD = new Map<string, IdiomDefinition>(
  IDIOM_DEFINITIONS.map(([word, brief, detail]) => [
    word,
    { brief, detail },
  ]),
)

export const findIdiomDefinition = (
  word: string,
): IdiomDefinition | null => DEFINITION_BY_WORD.get(word) ?? null
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, source, 'utf8')
console.log(`Generated ${entries.length} idiom definitions in ${outputPath}`)
