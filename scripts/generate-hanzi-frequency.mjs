import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import subtlexChChr from 'subtlex-ch-chr'

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)))
const outputPath = join(rootDir, 'src', 'data', 'hanziFrequency.ts')
const commonLimit = 3500

const characters = [
  ...new Set(
    subtlexChChr.data
      .filter(
        (row) =>
          typeof row.Character === 'string' &&
          Array.from(row.Character).length === 1 &&
          /\p{Script=Han}/u.test(row.Character) &&
          row.CHRCount > 0,
      )
      .sort((left, right) => right.CHRCount - left.CHRCount)
      .map((row) => row.Character),
  ),
]

const chunks = characters.join('').match(/.{1,80}/gu) ?? []
const orderLiteral = chunks.map((chunk) => `  '${chunk}'`).join(' +\n')

const source = `// Generated by scripts/generate-hanzi-frequency.mjs.
// Source: SUBTLEX-CH-CHR via the MIT-licensed subtlex-ch-chr package.
// See THIRD_PARTY_NOTICES.md for attribution.

export const COMMON_HANZI_LIMIT = ${commonLimit}

export const HANZI_FREQUENCY_ORDER =
${orderLiteral}

export const HANZI_FREQUENCY_RANK: ReadonlyMap<string, number> = new Map(
  Array.from(HANZI_FREQUENCY_ORDER).map((character, index) => [
    character,
    index,
  ]),
)
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, source, 'utf8')
console.log(
  `Generated ${characters.length} ranked characters in ${outputPath}`,
)
